#!/usr/bin/env python3
"""Regenerates ../fisb_stations.js.

argv[1]: https://aviationweather.gov/data/cache/stations.cache.json.gz
argv[2]: https://davidmegginson.github.io/ourairports-data/navaids.csv
"""
import csv, gzip, json, os, sys

DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'
REGIONS = ('US', 'PR', 'VI', 'GU', 'MP', 'AS')


def base36(value):
    return DIGITS[value // 1296] + DIGITS[value // 36 % 36] + DIGITS[value % 36]


def position(lat, lon):
    return base36(round((float(lat) + 90) * 100)) + base36(round((float(lon) + 180) * 100))


stations = sorted(
    s['icaoId'] + position(s['lat'], s['lon'])
    for s in json.load(gzip.open(sys.argv[1]))
    if s.get('country') in REGIONS and len(s.get('icaoId') or '') == 4 and s.get('siteType'))
navaids = sorted(
    n['ident'] + position(n['latitude_deg'], n['longitude_deg']) +
    DIGITS[round((float(n['slaved_variation_deg'] or n['magnetic_variation_deg'] or 0) + 21) / 1.5)]
    for n in csv.DictReader(open(sys.argv[2], newline='', encoding='utf-8'))
    if n['iso_country'] in REGIONS and n['type'] in ('VOR', 'VORTAC', 'VOR-DME', 'TACAN', 'DME') and len(n['ident']) == 3)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'fisb_stations.js')
with open(out, 'w') as f:
    f.write('// US weather station and navaid positions for fisb.js. Generated by test/make_fisb_stations.py.\n'
            '// Stations, "|", navaids. Positions: latitude + 90 and longitude + 180 in 0.01 degree steps, base 36.\n'
            '// Station: 4-letter id, position. Navaid: 3-letter id, position, magnetic variation east (digit * 1.5 - 21 degrees).\n'
            '(function (root) {\n'
            "    const data = '%s|%s';\n"
            "    if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
            '    else root.FISB_STATIONS = data;\n'
            "})(typeof window !== 'undefined' ? window : globalThis);\n" % (''.join(stations), ''.join(navaids)))
print(len(stations), 'stations', len(navaids), 'navaids')

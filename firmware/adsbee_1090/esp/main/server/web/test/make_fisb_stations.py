#!/usr/bin/env python3
"""Regenerates ../fisb_stations.js from https://aviationweather.gov/data/cache/stations.cache.json.gz (path in argv[1])."""
import gzip, json, os, sys

DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'


def base36(value):
    return DIGITS[value // 1296] + DIGITS[value // 36 % 36] + DIGITS[value % 36]


stations = json.load(gzip.open(sys.argv[1]))
rows = sorted(
    s['icaoId'] + base36(round((s['lat'] + 90) * 100)) + base36(round((s['lon'] + 180) * 100))
    for s in stations
    if s.get('country') in ('US', 'PR', 'VI', 'GU', 'MP', 'AS') and len(s.get('icaoId') or '') == 4 and s.get('siteType'))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'fisb_stations.js')
with open(out, 'w') as f:
    f.write('// US weather station positions for fisb.js. Generated by test/make_fisb_stations.py.\n'
            '// Each entry: 4-letter id, then latitude + 90 and longitude + 180 in 0.01 degree steps, base 36.\n'
            '(function (root) {\n'
            "    const data = '%s';\n"
            "    if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
            '    else root.FISB_STATIONS = data;\n'
            "})(typeof window !== 'undefined' ? window : globalThis);\n" % ''.join(rows))
print(len(rows), 'stations')
